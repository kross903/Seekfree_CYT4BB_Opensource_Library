#ifndef _FLOW_SENSOR_CONFIG_H_
#define _FLOW_SENSOR_CONFIG_H_

#define FLOW_SENSOR_PMW3901       0
#define FLOW_SENSOR_UPFLOW302     1

/* Change this one macro to switch optical-flow hardware. */
#define FLOW_SENSOR_SELECTED      FLOW_SENSOR_UPFLOW302

#define FLOW_SENSOR_PMW3901_UPDATE_US       (20000U)
#define FLOW_SENSOR_PMW3901_DT_S            (0.020f)
#define FLOW_SENSOR_PMW3901_RAD_PER_COUNT_X (1.0f / 385.0f)
#define FLOW_SENSOR_PMW3901_RAD_PER_COUNT_Y (1.0f / 385.0f)
#define FLOW_SENSOR_PMW3901_X_SIGN          (1.0f)
#define FLOW_SENSOR_PMW3901_Y_SIGN          (1.0f)
#define FLOW_SENSOR_PMW3901_SWAP_XY         (0)

#define FLOW_SENSOR_UPFLOW302_UPDATE_US       (25000U)
#define FLOW_SENSOR_UPFLOW302_DT_S            (0.025f)
#define FLOW_SENSOR_UPFLOW302_RAD_PER_COUNT_X (1.0f / 10000.0f)
#define FLOW_SENSOR_UPFLOW302_RAD_PER_COUNT_Y (1.0f / 10000.0f)
/* Start with PMW3901 convention; if front/back or left/right is reversed, flip sign.
 * If pushing forward changes Y instead of X, keep signs and set SWAP_XY to 1. */
#define FLOW_SENSOR_UPFLOW302_X_SIGN          (-1.0f)
#define FLOW_SENSOR_UPFLOW302_Y_SIGN          (-1.0f)
#define FLOW_SENSOR_UPFLOW302_SWAP_XY         (0)
#define FLOW_SENSOR_UPFLOW302_VALID_VALUE     (245U)

#if FLOW_SENSOR_SELECTED == FLOW_SENSOR_PMW3901
#define FLOW_SENSOR_UPDATE_US       FLOW_SENSOR_PMW3901_UPDATE_US
#define FLOW_SENSOR_NOMINAL_DT_S    FLOW_SENSOR_PMW3901_DT_S
#define FLOW_SENSOR_RAD_PER_COUNT_X FLOW_SENSOR_PMW3901_RAD_PER_COUNT_X
#define FLOW_SENSOR_RAD_PER_COUNT_Y FLOW_SENSOR_PMW3901_RAD_PER_COUNT_Y
#define FLOW_SENSOR_X_SIGN          FLOW_SENSOR_PMW3901_X_SIGN
#define FLOW_SENSOR_Y_SIGN          FLOW_SENSOR_PMW3901_Y_SIGN
#define FLOW_SENSOR_SWAP_XY         FLOW_SENSOR_PMW3901_SWAP_XY
#elif FLOW_SENSOR_SELECTED == FLOW_SENSOR_UPFLOW302
#define FLOW_SENSOR_UPDATE_US       FLOW_SENSOR_UPFLOW302_UPDATE_US
#define FLOW_SENSOR_NOMINAL_DT_S    FLOW_SENSOR_UPFLOW302_DT_S
#define FLOW_SENSOR_RAD_PER_COUNT_X FLOW_SENSOR_UPFLOW302_RAD_PER_COUNT_X
#define FLOW_SENSOR_RAD_PER_COUNT_Y FLOW_SENSOR_UPFLOW302_RAD_PER_COUNT_Y
#define FLOW_SENSOR_X_SIGN          FLOW_SENSOR_UPFLOW302_X_SIGN
#define FLOW_SENSOR_Y_SIGN          FLOW_SENSOR_UPFLOW302_Y_SIGN
#define FLOW_SENSOR_SWAP_XY         FLOW_SENSOR_UPFLOW302_SWAP_XY
#else
#error "Invalid FLOW_SENSOR_SELECTED"
#endif

#endif