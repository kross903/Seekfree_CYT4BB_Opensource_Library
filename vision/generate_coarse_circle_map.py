#!/usr/bin/env python3
"""Generate the firmware coarse-threshold concentric-circle lookup table."""

from __future__ import annotations

import argparse
import bisect
import math
import re
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_PARAMS = REPO_ROOT / "project/code/vision/camera_calibration_params.h"
DEFAULT_OUTPUT = REPO_ROOT / "project/code/vision/coarse_distance_zone_map.h"
DEFAULT_FRACTIONS = (0.20, 0.20, 0.10, 0.20, 0.30)


def read_macro(text: str, name: str) -> float:
    pattern = rf"^\s*#define\s+{re.escape(name)}\s+\(([^)]+)\)"
    match = re.search(pattern, text, flags=re.MULTILINE)
    if match is None:
        raise ValueError(f"missing macro: {name}")
    value = match.group(1).strip().rstrip("fFuUlL")
    return float(value)


def load_calibration(path: Path) -> tuple[int, int, float, float]:
    text = path.read_text(encoding="utf-8")
    width = int(read_macro(text, "CAMERA_CALIBRATION_IMAGE_WIDTH"))
    height = int(read_macro(text, "CAMERA_CALIBRATION_IMAGE_HEIGHT"))
    center_x = read_macro(text, "CAMERA_CALIBRATION_CX")
    center_y = read_macro(text, "CAMERA_CALIBRATION_CY")
    return width, height, center_x, center_y


def build_zones(
    width: int,
    height: int,
    center_x: float,
    center_y: float,
    fractions: tuple[float, float, float, float, float],
) -> tuple[list[int], list[float], list[int]]:
    if width <= 0 or height <= 0:
        raise ValueError("image dimensions must be positive")
    if len(fractions) != 5 or any(value <= 0.0 for value in fractions):
        raise ValueError("five positive zone fractions are required")
    if not math.isclose(sum(fractions), 1.0, rel_tol=0.0, abs_tol=1e-9):
        raise ValueError("zone fractions must sum to 1.0")

    radius_sq = [
        (x - center_x) ** 2 + (y - center_y) ** 2
        for y in range(height)
        for x in range(width)
    ]
    ordered = sorted(radius_sq)
    total = len(ordered)
    cumulative = 0.0
    cutoffs: list[float] = []

    for fraction in fractions[:-1]:
        cumulative += fraction
        rank = max(1, min(total - 1, round(total * cumulative)))
        while rank < total and ordered[rank] == ordered[rank - 1]:
            rank += 1
        if rank >= total:
            rank = total - 1
        cutoffs.append(0.5 * (ordered[rank - 1] + ordered[rank]))

    zones = [bisect.bisect_right(cutoffs, value) for value in radius_sq]
    counts = [zones.count(zone) for zone in range(5)]
    return zones, cutoffs, counts


def render_header(
    width: int,
    height: int,
    center_x: float,
    center_y: float,
    fractions: tuple[float, float, float, float, float],
    zones: list[int],
    cutoffs: list[float],
    counts: list[int],
) -> str:
    total = width * height
    fraction_text = ", ".join(f"{value * 100.0:.1f}%" for value in fractions)
    actual_text = ", ".join(f"{count * 100.0 / total:.3f}%" for count in counts)
    radius_text = ", ".join(f"{math.sqrt(value):.6f}" for value in cutoffs)
    lines = [
        "#ifndef VISION_COARSE_DISTANCE_ZONE_MAP_H_",
        "#define VISION_COARSE_DISTANCE_ZONE_MAP_H_",
        "",
        "/* Generated by vision/generate_coarse_circle_map.py.",
        f" * Image: {width}x{height}; optical center: ({center_x:.7f}, {center_y:.7f}).",
        f" * Requested area shares: {fraction_text}.",
        f" * Actual area shares: {actual_text}.",
        f" * Circle boundary radii in source pixels: {radius_text}.",
        " */",
        "static const uint8 g_vision_coarse_distance_zone[MT9V03X_H * MT9V03X_W] =",
        "{",
    ]
    for offset in range(0, len(zones), 32):
        values = zones[offset:offset + 32]
        suffix = "," if offset + 32 < len(zones) else ""
        lines.append("    " + ", ".join(str(value) for value in values) + suffix)
    lines.extend([
        "};",
        "",
        "#endif /* VISION_COARSE_DISTANCE_ZONE_MAP_H_ */",
    ])
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--params", type=Path, default=DEFAULT_PARAMS)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--fractions",
        type=float,
        nargs=5,
        default=DEFAULT_FRACTIONS,
        metavar=("CENTER", "NEAR", "MIDDLE", "FAR", "EDGE"),
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    fractions = tuple(args.fractions)
    width, height, center_x, center_y = load_calibration(args.params)
    zones, cutoffs, counts = build_zones(
        width, height, center_x, center_y, fractions
    )
    content = render_header(
        width, height, center_x, center_y, fractions, zones, cutoffs, counts
    )

    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != content:
            print(f"out of date: {args.output}")
            return 1
    else:
        args.output.write_text(content, encoding="utf-8", newline="\n")

    percentages = [count * 100.0 / (width * height) for count in counts]
    print("counts=" + ",".join(str(count) for count in counts))
    print("percentages=" + ",".join(f"{value:.3f}" for value in percentages))
    print("radii_px=" + ",".join(f"{math.sqrt(value):.6f}" for value in cutoffs))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
